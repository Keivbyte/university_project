//
// Общий сетевой интерфейс, не зависящий от платформы.
//
// Клиент (Windows) реализует его через Winsock, сервер (Linux/Pi) — через
// POSIX-сокеты. Весь код выше этого слоя (протокол, сериализация, синхронизация
// состояния) не должен знать, какая ОС под ним.
//
// Что здесь предстоит определить на этапе 24-25:
//   - тип дескриптора сокета (на Windows SOCKET/UINT_PTR, на Linux int),
//     скрытый за общим псевдонимом;
//   - обёртки над socket/bind/listen/accept/connect/send/recv/close;
//   - единая модель ошибок (на Windows WSAGetLastError, на Linux errno);
//   - разделение TCP и UDP;
//   - неблокирующий режим для игрового цикла сервера.
//
// Платформенные различия инициализации:
//   - Windows требует WSAStartup/WSACleanup — на Linux их нет;
//   - closesocket (Windows) vs close (Linux);
//   - заголовки: <winsock2.h>/<ws2tcpip.h> vs <sys/socket.h>/<netinet/in.h>.
//
// Реализация будет разветвлена по платформе (см. client/net и server/net),
// а этот заголовок остаётся общим контрактом.